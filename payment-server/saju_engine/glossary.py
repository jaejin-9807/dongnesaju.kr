def find_terms_in_text(text: str) -> list:
    """본문 텍스트에서 GLOSSARY에 등록된 용어가 등장하는지 찾아 그 목록을 반환한다.
    긴 용어(예: '천을귀인')를 먼저 찾고, 이미 매칭된 부분과 겹치는 짧은 용어는
    중복 각주를 피하기 위해 제외한다."""
    if not text:
        return []
    found = []
    # 용어를 길이 내림차순으로 검사해 부분 문자열 중복(예: '용신'과 '용신·희신') 방지
    for term in sorted(GLOSSARY.keys(), key=len, reverse=True):
        if term in text:
            # 이미 찾은 용어 중 하나가 이 term을 포함하고 있으면(더 긴 용어로 이미 처리됨) 건너뜀
            if any(term in existing and term != existing for existing in found):
                continue
            found.append(term)
    return found


def build_footnote_html(text: str, max_terms: int = 4) -> str:
    """본문 텍스트 하나에 대해 각주 HTML 문자열을 만들어 반환한다. 용어가 없으면 빈 문자열."""
    terms = find_terms_in_text(text)[:max_terms]
    if not terms:
        return ""
    import html as _html
    items = "".join(
        f"<div class='footnote-item'><b>*{_html.escape(t)}</b> : {_html.escape(GLOSSARY[t])}</div>"
        for t in terms
    )
    return f"<div class='footnote-box'>{items}</div>"
