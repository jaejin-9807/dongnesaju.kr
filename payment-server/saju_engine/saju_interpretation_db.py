def _josa(word: str, has_batchim_form: str, no_batchim_form: str) -> str:
    """마지막 글자 받침 유무에 따라 '이/가', '은/는', '을/를' 등 조사를 자동 선택한다."""
    if not word:
        return no_batchim_form
    last = word[-1]
    code = ord(last) - 0xAC00
    if 0 <= code <= 11171:
        has_batchim = (code % 28) != 0
        return has_batchim_form if has_batchim else no_batchim_form
    return no_batchim_form


