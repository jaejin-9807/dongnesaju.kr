# 십성(十星) 산출표
# 일간(日干)의 음양오행을 기준으로 대상 천간/지지 오행과의 생극 관계 + 음양 일치여부로 결정.
# 표준 십성 판정 로직(자평명리 표준):
#   대상오행이 일간오행과 같음      : 음양 같으면 비견, 다르면 겁재
#   대상오행이 일간오행을 생함(인성) : 음양 같으면 편인, 다르면 정인
#   대상오행이 일간오행을 극함(관성) : 음양 같으면 편관(칠살), 다르면 정관
#   일간오행이 대상오행을 극함(재성) : 음양 같으면 편재, 다르면 정재
#   일간오행이 대상오행을 생함(식상) : 음양 같으면 식신, 다르면 상관
# -----------------------------
def get_sipseong(ilgan: str, target_gan: str) -> str:
    """
    ilgan: 일간(예: '갑')
    target_gan: 비교 대상 천간(예: '병') - 사주 내 다른 천간 또는 지장간의 천간
    반환: 십성 이름
    """
    ilgan_oheng = CHEONGAN_OHENG[ilgan]
    ilgan_eumyang = CHEONGAN_EUMYANG[ilgan]
    target_oheng = CHEONGAN_OHENG[target_gan]
    target_eumyang = CHEONGAN_EUMYANG[target_gan]

    same_eumyang = (ilgan_eumyang == target_eumyang)

    if target_oheng == ilgan_oheng:
        return "비견" if same_eumyang else "겁재"
    elif SANGSAENG[target_oheng] == ilgan_oheng:
        # 대상오행이 일간오행을 생함 -> 인성
        return "편인" if same_eumyang else "정인"
    elif SANGGEUK[target_oheng] == ilgan_oheng:
        # 대상오행이 일간오행을 극함 -> 관성
        return "편관" if same_eumyang else "정관"
    elif SANGGEUK[ilgan_oheng] == target_oheng:
        # 일간오행이 대상오행을 극함 -> 재성
        return "편재" if same_eumyang else "정재"
    elif SANGSAENG[ilgan_oheng] == target_oheng:
        # 일간오행이 대상오행을 생함 -> 식상
        return "식신" if same_eumyang else "상관"
    else:
        return "미정"


# -----------------------------
# 12운성(十二運星) 표
# 각 천간이 12지지를 만났을 때의 기세(장생~묘) 표준표.
# 순서: 장생, 목욕, 관대, 건록, 제왕, 쇠, 병, 사, 묘, 절, 태, 양
# 양간은 순행(시계방향), 음간은 역행.
# -----------------------------
SIB_IWSEONG_ORDER = ["장생", "목욕", "관대", "건록", "제왕", "쇠", "병", "사", "묘", "절", "태", "양"]

# 양간의 장생 위치(양간 순행의 기준점)
YANGGAN_JANGSAENG = {
    "갑": "해", "병": "인", "무": "인", "경": "사", "임": "신",
}
# 음간의 장생 위치(음간 역행의 기준점)
EUMGAN_JANGSAENG = {
    "을": "오", "정": "유", "기": "유", "신": "자", "계": "묘",
}


def get_12unseong(gan: str, ji: str) -> str:
    """천간 gan이 지지 ji를 만났을 때의 12운성을 반환."""
    eumyang = CHEONGAN_EUMYANG[gan]
    if eumyang == "양":
        start = YANGGAN_JANGSAENG[gan]
        start_idx = JIJI.index(start)
        target_idx = JIJI.index(ji)
        offset = (target_idx - start_idx) % 12  # 순행
    else:
        start = EUMGAN_JANGSAENG[gan]
        start_idx = JIJI.index(start)
        target_idx = JIJI.index(ji)
        offset = (start_idx - target_idx) % 12  # 역행
    return SIB_IWSEONG_ORDER[offset]


