# 상생: 목생화, 화생토, 토생금, 금생수, 수생목
SANGSAENG = {
    "목": "화", "화": "토", "토": "금", "금": "수", "수": "목",
}
# 상극: 목극토, 토극수, 수극화, 화극금, 금극목
SANGGEUK = {
    "목": "토", "토": "수", "수": "화", "화": "금", "금": "목",
}


def get_sangsaeng_relation(a: str, b: str) -> str:
    """a가 b에 대해 상생상극상 어떤 관계인지 반환."""
    if SANGSAENG[a] == b:
        return f"{a}생{b}(상생)"
    if SANGSAENG[b] == a:
        return f"{b}생{a}(상생, {a}는 {b}의 도움을 받음)"
    if SANGGEUK[a] == b:
        return f"{a}극{b}(상극)"
    if SANGGEUK[b] == a:
        return f"{b}극{a}(상극, {a}가 {b}의 극제를 받음)"
    if a == b:
        return "비화(比和, 동일오행)"
    return "무관계"


